import {readFileSync,readdirSync} from 'node:fs';
import assert from 'node:assert/strict';
import {verifySnapshot} from '../docs/integrity.mjs';
const dir=process.argv[2];
const d=await verifySnapshot(JSON.parse(readFileSync(dir+'/snapshot.json','utf8')));
assert.equal(d.evidence.mode,'public_beta');
const manifest=JSON.parse(readFileSync(dir+'/release.json','utf8'));
assert.deepEqual(manifest,{version:1,cutoff:d.cutoff,snapshot_digest:d.digest,evidence_digest:d.evidence.digest});
const a=d.evidence.current_trace_audit;
assert.equal(a.total_traces,d.trace_count);
assert.equal(a.matched+a.mismatch+a.unavailable+a.pending,a.total_traces);
assert.ok(a.matched_with_swaps<=a.matched);
assert.equal(Object.values(a.mismatch_reasons).reduce((sum,n)=>sum+n,0),a.mismatch);
assert.equal(d.evidence.swap_audit.checked,0);
assert.equal(d.evidence.swap_audit.status,'partial');
assert.ok(d.evidence.seed_audit.attempted<=d.evidence.seed_audit.total_traces);
assert.deepEqual(readdirSync(dir).sort(),['index.html','styles.css','telegram.svg','app.mjs','analytics.mjs','integrity.mjs','wallets.mjs','wallet-ui.mjs','cost-basis.mjs','snapshot.json','release.json'].sort());
console.log('Public beta validated: no raw working data, secrets, or false audit claims in deployment artifact');
